static void draw_header(Canvas* canvas, const char* title, const char* indicator) {
    canvas_set_font(canvas, FontPrimary);
    canvas_draw_str(canvas, 2, 10, title);
    canvas_set_font(canvas, FontSecondary);
    if(indicator) canvas_draw_str_aligned(canvas, 126, 2, AlignRight, AlignTop, indicator);
    canvas_draw_line(canvas, 0, 13, 127, 13);
}

static void draw_password_screen(Canvas* canvas, const App* app, const LangStrings* s) {
    const char* title = app->screen == ScreenCreate  ? s->title_create :
                        app->screen == ScreenConfirm ? s->title_confirm :
                                                       s->title_unlock;
    draw_header(canvas, title, NULL);

    char stars[PW_MAX + 1];
    memset(stars, '*', app->pw_len);
    stars[app->pw_len] = 0;
    canvas_draw_str(canvas, 2, 26, stars);

    char cur[2] = {PW_CHARSET[app->pw_cur], 0};
    canvas_draw_frame(canvas, 2, 29, 14, 13);
    canvas_draw_str_aligned(canvas, 9, 36, AlignCenter, AlignCenter, cur);
    canvas_draw_str(canvas, 20, 39, s->pw_hint1);
    canvas_draw_str(canvas, 2, 51, s->pw_hint2);

    char text[40];
    if(app->msg_until && (int32_t)(app->msg_until - furi_get_tick()) > 0) {
        canvas_draw_str(canvas, 2, 62, app->msg);
    } else if(app->screen == ScreenUnlock && is_waiting(app)) {
        uint32_t secs = (app->wait_until - furi_get_tick() + 999) / 1000;
        snprintf(text, sizeof(text), s->msg_wait, (unsigned long)secs);
        canvas_draw_str(canvas, 2, 62, text);
    } else {
        canvas_draw_str(canvas, 2, 62, s->pw_hint3);
    }
}

static void draw_codes_page(Canvas* canvas, const App* app, const LangStrings* s) {
    char text[40];
    if(app->acc_count == 0) {
        canvas_draw_str_aligned(canvas, 64, 34, AlignCenter, AlignBottom, s->no_accounts);
        canvas_draw_str_aligned(canvas, 64, 46, AlignCenter, AlignBottom, s->no_accounts_hint);
        return;
    }

    const Account* a = &app->acc[app->sel];
    canvas_draw_str_aligned(canvas, 64, 25, AlignCenter, AlignBottom, a->name);

    char digits[12];
    snprintf(digits, sizeof(digits), "%0*lu", (int)a->digits, (unsigned long)account_code(app, a));
    char left[8] = {0};
    char right[8] = {0};
    size_t half = a->digits / 2;
    memcpy(left, digits, half);
    memcpy(right, digits + half, a->digits - half);
    canvas_set_font(canvas, FontBigNumbers);
    canvas_draw_str_aligned(canvas, 60, 44, AlignRight, AlignBottom, left);
    canvas_draw_str_aligned(canvas, 68, 44, AlignLeft, AlignBottom, right);
    canvas_set_font(canvas, FontSecondary);

    uint32_t remaining = a->period - (utc_now(app) % a->period);
    canvas_draw_frame(canvas, 2, 49, 124, 5);
    canvas_draw_box(canvas, 4, 51, (uint8_t)(remaining * 120 / a->period), 1);

    if(clock_looks_wrong()) {
        canvas_draw_str(canvas, 2, 63, s->clock_warn);
    } else {
        canvas_draw_str(canvas, 2, 63, s->hint_type);
    }
    snprintf(text, sizeof(text), "%u/%u", app->sel + 1, app->acc_count);
    canvas_draw_str_aligned(canvas, 126, 63, AlignRight, AlignBottom, text);
}

static void draw_import_page(Canvas* canvas, const App* app, const LangStrings* s) {
    canvas_draw_str(canvas, 2, 24, s->imp_1);
    canvas_draw_str(canvas, 2, 33, s->imp_2);
    canvas_draw_str(canvas, 2, 42, s->imp_3);
    canvas_draw_str(canvas, 2, 52, s->imp_ok);
    if(app->msg_until && (int32_t)(app->msg_until - furi_get_tick()) > 0) {
        canvas_draw_str(canvas, 2, 62, app->msg);
    }
}

static void draw_settings_page(Canvas* canvas, const App* app, const LangStrings* s) {
    const char* labels[SETTINGS_ROWS] = {s->lbl_language, s->lbl_utc, s->lbl_digits, s->lbl_lock};
    char values[SETTINGS_ROWS][20];
    snprintf(values[SET_LANGUAGE], sizeof(values[0]), "%s", LANGUAGES[app->lang]->lang_name);
    int abs_min = app->utc_min < 0 ? -app->utc_min : app->utc_min;
    snprintf(
        values[SET_UTC],
        sizeof(values[0]),
        "%c%02d:%02d",
        app->utc_min < 0 ? '-' : '+',
        abs_min / 60,
        abs_min % 60);
    snprintf(
        values[SET_DIGITS],
        sizeof(values[0]),
        "%s",
        app->digits_pad ? s->digits_pad : s->digits_top);
    uint16_t lock_secs = LOCK_SECONDS[app->lock_idx];
    if(lock_secs < 60) {
        snprintf(values[SET_LOCK], sizeof(values[0]), "%u s", lock_secs);
    } else {
        snprintf(values[SET_LOCK], sizeof(values[0]), "%u min", lock_secs / 60);
    }

    for(uint8_t i = 0; i < SETTINGS_ROWS; i++) {
        uint8_t y = 25 + i * 10;
        if(i == app->settings_sel) canvas_draw_str(canvas, 0, y, ">");
        canvas_draw_str(canvas, 7, y, labels[i]);
        canvas_draw_str(canvas, 70, y, values[i]);
    }
}

