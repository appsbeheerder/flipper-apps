static bool file_read_all(Storage* st, const char* path, uint8_t* buf, size_t max, size_t* out_len) {
    File* f = storage_file_alloc(st);
    bool ok = false;
    if(storage_file_open(f, path, FSAM_READ, FSOM_OPEN_EXISTING)) {
        *out_len = storage_file_read(f, buf, max);
        ok = true;
    }
    storage_file_close(f);
    storage_file_free(f);
    return ok;
}

static bool file_write_all(Storage* st, const char* path, const uint8_t* buf, size_t len) {
    File* f = storage_file_alloc(st);
    bool ok = false;
    if(storage_file_open(f, path, FSAM_WRITE, FSOM_CREATE_ALWAYS)) {
        ok = storage_file_write(f, buf, len) == len;
    }
    storage_file_close(f);
    storage_file_free(f);
    return ok;
}

// password -> PBKDF2 -> enclave (unique key, slot 11) -> 32-byte vault key.
static bool derive_key(const char* pw, const uint8_t* salt, uint32_t iters, uint8_t* key_out) {
    uint8_t k1[32];
    static const uint8_t iv0[16] = {0};
    bool ok = false;

    pbkdf2_hmac_sha256((const uint8_t*)pw, strlen(pw), salt, SALT_LEN, iters, k1);

    if(furi_hal_crypto_enclave_ensure_key(FURI_HAL_CRYPTO_ENCLAVE_UNIQUE_KEY_SLOT) &&
       furi_hal_crypto_enclave_load_key(FURI_HAL_CRYPTO_ENCLAVE_UNIQUE_KEY_SLOT, iv0)) {
        ok = furi_hal_crypto_encrypt(k1, key_out, 32);
        furi_hal_crypto_enclave_unload_key(FURI_HAL_CRYPTO_ENCLAVE_UNIQUE_KEY_SLOT);
    }
    secure_zero(k1, sizeof(k1));
    return ok;
}

static uint32_t calibrate_iterations(void) {
    uint8_t salt[SALT_LEN] = {0};
    uint8_t out[32];
    uint32_t t0 = furi_get_tick();
    pbkdf2_hmac_sha256((const uint8_t*)"calibrate", 9, salt, SALT_LEN, 1000, out);
    uint32_t ms = furi_get_tick() - t0;
    if(ms == 0) ms = 1;
    uint64_t iters = (uint64_t)1000 * KDF_TARGET_MS / ms;
    if(iters < KDF_MIN_ITERS) iters = KDF_MIN_ITERS;
    if(iters > KDF_MAX_ITERS) iters = KDF_MAX_ITERS;
    return (uint32_t)iters;
}

static void serialize_accounts(const App* app, uint8_t* plain) {
    memset(plain, 0, PLAIN_LEN);
    plain[0] = app->acc_count;
    for(uint8_t i = 0; i < app->acc_count; i++) {
        uint8_t* r = plain + 1 + i * REC_LEN;
        const Account* a = &app->acc[i];
        memcpy(r, a->name, NAME_LEN);
        r[NAME_LEN] = a->algo;
        r[NAME_LEN + 1] = a->digits;
        r[NAME_LEN + 2] = a->period;
        r[NAME_LEN + 3] = a->secret_len;
        memcpy(r + NAME_LEN + 4, a->secret, SECRET_MAX);
    }
}

static bool parse_accounts(App* app, const uint8_t* plain) {
    if(plain[0] > MAX_ACCOUNTS) return false;
    app->acc_count = plain[0];
    for(uint8_t i = 0; i < app->acc_count; i++) {
        const uint8_t* r = plain + 1 + i * REC_LEN;
        Account* a = &app->acc[i];
        memcpy(a->name, r, NAME_LEN);
        a->name[NAME_LEN - 1] = 0;
        a->algo = r[NAME_LEN];
        a->digits = r[NAME_LEN + 1];
        a->period = r[NAME_LEN + 2];
        a->secret_len = r[NAME_LEN + 3];
        memcpy(a->secret, r + NAME_LEN + 4, SECRET_MAX);
        if(a->algo > OtpSha256 || a->digits < 6 || a->digits > 8 || a->period < 10 ||
           a->period > 120 || a->secret_len == 0 || a->secret_len > SECRET_MAX) {
            return false;
        }
    }
    return true;
}

static bool vault_save(App* app) {
    uint8_t* plain = malloc(PLAIN_LEN);
    uint8_t* file = malloc(FILE_LEN);
    bool ok = false;

    serialize_accounts(app, plain);

    memcpy(file, VAULT_MAGIC, 4);
    file[4] = VAULT_VERSION;
    for(int i = 0; i < 4; i++) file[5 + i] = (uint8_t)(app->iters >> (8 * i));
    memcpy(file + 9, app->salt, SALT_LEN);
    furi_hal_random_fill_buf(file + 9 + SALT_LEN, IV_LEN);

    if(furi_hal_crypto_gcm_encrypt_and_tag(
           app->key,
           file + 9 + SALT_LEN,
           file,
           HDR_LEN,
           plain,
           file + HDR_LEN + TAG_LEN,
           PLAIN_LEN,
           file + HDR_LEN) == FuriHalCryptoGCMStateOk) {
        storage_simply_mkdir(app->storage, DATA_DIR);
        if(file_write_all(app->storage, VAULT_TMP_PATH, file, FILE_LEN)) {
            storage_simply_remove(app->storage, VAULT_PATH);
            ok = storage_common_rename(app->storage, VAULT_TMP_PATH, VAULT_PATH) == FSE_OK;
        }
    }

    secure_zero(plain, PLAIN_LEN);
    free(plain);
    free(file);
    return ok;
}

typedef enum {
    VaultOk,
    VaultCorrupt,
    VaultWrongPassword,
} VaultResult;

static VaultResult vault_load(App* app) {
    uint8_t* file = malloc(FILE_LEN);
    uint8_t* plain = malloc(PLAIN_LEN);
    size_t len = 0;
    VaultResult result = VaultCorrupt;

    if(file_read_all(app->storage, VAULT_PATH, file, FILE_LEN, &len) && len == FILE_LEN &&
       memcmp(file, VAULT_MAGIC, 4) == 0 && file[4] == VAULT_VERSION) {
        uint32_t iters = 0;
        for(int i = 0; i < 4; i++) iters |= (uint32_t)file[5 + i] << (8 * i);
        if(iters >= 1000 && iters <= 2000000u) {
            memcpy(app->salt, file + 9, SALT_LEN);
            app->iters = iters;
            if(derive_key(app->pw, app->salt, iters, app->key)) {
                FuriHalCryptoGCMState st = furi_hal_crypto_gcm_decrypt_and_verify(
                    app->key,
                    file + 9 + SALT_LEN,
                    file,
                    HDR_LEN,
                    file + HDR_LEN + TAG_LEN,
                    plain,
                    PLAIN_LEN,
                    file + HDR_LEN);
                if(st == FuriHalCryptoGCMStateOk) {
                    result = parse_accounts(app, plain) ? VaultOk : VaultCorrupt;
                } else if(st == FuriHalCryptoGCMStateAuthFailure) {
                    result = VaultWrongPassword;
                }
            }
        }
    }

    secure_zero(plain, PLAIN_LEN);
    free(plain);
    free(file);
    if(result != VaultOk) secure_zero(app->key, sizeof(app->key));
    return result;
}

//======================================================================================================================
// Import (import.txt: "Name;BASE32SECRET[;sha1|sha256[;digits[;period]]]" per line)
//======================================================================================================================

static bool str_ieq(const char* a, const char* b) {
    for(; *a && *b; a++, b++) {
        char x = (*a >= 'A' && *a <= 'Z') ? (char)(*a + 32) : *a;
        char y = (*b >= 'A' && *b <= 'Z') ? (char)(*b + 32) : *b;
        if(x != y) return false;
    }
    return *a == *b;
}

static bool parse_import_line(char* line, Account* a) {
    char* fields[5] = {line, NULL, NULL, NULL, NULL};
    int n = 1;
    for(char* p = line; *p && n < 5; p++) {
        if(*p == ';') {
            *p = 0;
            fields[n++] = p + 1;
        }
    }
    if(n < 2 || fields[0][0] == 0) return false;

    memset(a, 0, sizeof(*a));
    snprintf(a->name, NAME_LEN, "%s", fields[0]);

    int len = base32_decode(fields[1], a->secret, SECRET_MAX);
    if(len <= 0) return false;
    a->secret_len = (uint8_t)len;

    a->algo = OtpSha1;
    if(n > 2 && fields[2][0]) {
        if(str_ieq(fields[2], "sha256")) {
            a->algo = OtpSha256;
        } else if(!str_ieq(fields[2], "sha1")) {
            return false;
        }
    }

    a->digits = 6;
    if(n > 3 && fields[3][0]) {
        int v = atoi(fields[3]);
        if(v < 6 || v > 8) return false;
        a->digits = (uint8_t)v;
    }

    a->period = 30;
    if(n > 4 && fields[4][0]) {
        int v = atoi(fields[4]);
        if(v < 10 || v > 120) return false;
        a->period = (uint8_t)v;
    }
    return true;
}

static void action_import(App* app) {
    const LangStrings* s = LANGUAGES[app->lang];
    char text[48];
    char* buf = malloc(IMPORT_MAX + 1);
    size_t len = 0;

    if(!file_read_all(app->storage, IMPORT_PATH, (uint8_t*)buf, IMPORT_MAX, &len)) {
        set_msg(app, s->imp_none);
        free(buf);
        return;
    }
    buf[len] = 0;

    Account added[MAX_ACCOUNTS];
    uint8_t added_count = 0;
    unsigned line_no = 0;
    bool bad = false;
    bool full = false;

    char* line = buf;
    while(line && *line) {
        char* next = strchr(line, '\n');
        if(next) *next++ = 0;
        line_no++;
        size_t ll = strlen(line);
        while(ll && (line[ll - 1] == '\r' || line[ll - 1] == ' ')) line[--ll] = 0;
        if(ll && line[0] != '#') {
            if(app->acc_count + added_count >= MAX_ACCOUNTS) {
                full = true;
                break;
            }
            if(!parse_import_line(line, &added[added_count])) {
                bad = true;
                break;
            }
            added_count++;
        }
        line = next;
    }

    if(bad) {
        snprintf(text, sizeof(text), s->imp_bad, line_no);
        set_msg(app, text);
    } else if(full) {
        set_msg(app, s->imp_full);
    } else if(added_count == 0) {
        set_msg(app, s->imp_none);
    } else {
        uint8_t old_count = app->acc_count;
        for(uint8_t i = 0; i < added_count; i++) app->acc[app->acc_count++] = added[i];
        if(vault_save(app)) {
            // Overwrite the plain-text secrets before deleting the file.
            memset(buf, 0, len);
            file_write_all(app->storage, IMPORT_PATH, (const uint8_t*)buf, len);
            storage_simply_remove(app->storage, IMPORT_PATH);
            snprintf(text, sizeof(text), s->imp_done, (unsigned)added_count);
            set_msg(app, text);
        } else {
            app->acc_count = old_count;
            set_msg(app, s->msg_save_fail);
        }
    }

    secure_zero(added, sizeof(added));
    secure_zero(buf, IMPORT_MAX + 1);
    free(buf);
}

//======================================================================================================================
// Time, codes and USB typing
//======================================================================================================================

static uint32_t utc_now(const App* app) {
    DateTime dt;
    furi_hal_rtc_get_datetime(&dt);
    int64_t ts = (int64_t)datetime_datetime_to_timestamp(&dt) - (int64_t)app->utc_min * 60;
    return ts < 0 ? 0 : (uint32_t)ts;
}

static bool clock_looks_wrong(void) {
    DateTime dt;
    furi_hal_rtc_get_datetime(&dt);
    return dt.year < APP_START_YEAR;
}

static uint32_t account_code(const App* app, const Account* a) {
    return totp_code(
        (OtpAlgo)a->algo, a->secret, a->secret_len, utc_now(app), a->period, a->digits);
}

static uint16_t hid_digit_key(bool numpad, char digit) {
    uint16_t d = (uint16_t)(digit - '0');
    if(numpad) return d == 0 ? 0x62 : (uint16_t)(0x59 + d - 1);
    return d == 0 ? 0x27 : (uint16_t)(0x1e + d - 1);
}

static void action_type(App* app) {
    const LangStrings* s = LANGUAGES[app->lang];
    const Account* a = &app->acc[app->sel];
    char digits[12];
    snprintf(digits, sizeof(digits), "%0*lu", (int)a->digits, (unsigned long)account_code(app, a));

    FuriHalUsbInterface* previous = furi_hal_usb_get_config();
    furi_hal_usb_unlock();
    furi_hal_usb_set_config(&usb_hid, NULL);

    uint32_t waited = 0;
    while(!furi_hal_hid_is_connected() && waited < 3000) {
        furi_delay_ms(50);
        waited += 50;
    }

    if(furi_hal_hid_is_connected()) {
        furi_delay_ms(300);
        for(const char* p = digits; *p; p++) {
            uint16_t key = hid_digit_key(app->digits_pad != 0, *p);
            furi_hal_hid_kb_press(key);
            furi_delay_ms(25);
            furi_hal_hid_kb_release(key);
            furi_delay_ms(25);
        }
        set_msg(app, s->msg_typed);
    } else {
        set_msg(app, s->msg_no_usb);
    }

    furi_hal_usb_set_config(previous, NULL);
    secure_zero(digits, sizeof(digits));
}

//======================================================================================================================
// Create / unlock / lock
//======================================================================================================================

static void wipe_password(App* app) {
    secure_zero(app->pw, sizeof(app->pw));
    secure_zero(app->pw_first, sizeof(app->pw_first));
    app->pw_len = 0;
    app->pw_cur = 0;
}

static void lock_vault(App* app) {
    secure_zero(app->key, sizeof(app->key));
    secure_zero(app->acc, sizeof(app->acc));
    app->acc_count = 0;
    app->sel = 0;
    app->page = PAGE_CODES;
    wipe_password(app);
    app->screen = ScreenUnlock;
}

static void action_create(App* app) {
    const LangStrings* s = LANGUAGES[app->lang];
    furi_hal_random_fill_buf(app->salt, SALT_LEN);
    app->iters = calibrate_iterations();
    app->acc_count = 0;

    if(derive_key(app->pw, app->salt, app->iters, app->key) && vault_save(app)) {
        wipe_password(app);
        app->page = PAGE_CODES;
        app->screen = ScreenMain;
    } else {
        secure_zero(app->key, sizeof(app->key));
        wipe_password(app);
        set_msg(app, s->msg_save_fail);
        app->screen = ScreenCreate;
    }
}

static void action_unlock(App* app) {
    const LangStrings* s = LANGUAGES[app->lang];
    VaultResult r = vault_load(app);
    if(r == VaultOk) {
        app->fails = 0;
        wipe_password(app);
        app->page = PAGE_CODES;
        app->screen = ScreenMain;
    } else if(r == VaultWrongPassword) {
        app->fails++;
        if(app->fails >= 3) {
            uint32_t shift = app->fails - 3;
            uint32_t secs = shift > 5 ? 120 : (5u << shift);
            if(secs > 120) secs = 120;
            app->wait_until = furi_get_tick() + secs * 1000;
        }
        wipe_password(app);
        set_msg(app, s->msg_wrong);
    } else {
        wipe_password(app);
        set_msg(app, s->msg_corrupt);
    }
}

static void run_action(App* app, Action act) {
    switch(act) {
    case ActCreate:
        action_create(app);
        break;
    case ActUnlock:
        action_unlock(app);
        break;
    case ActImport:
        action_import(app);
        break;
    case ActType:
        action_type(app);
        break;
    default:
        break;
    }
}

