static void settings_change(App* app) {
    switch(app->settings_sel) {
    case SET_LANGUAGE:
        app->lang = (uint8_t)((app->lang + 1) % LANGUAGE_COUNT);
        break;
    case SET_UTC:
        app->utc_min = (int16_t)(app->utc_min + 30);
        if(app->utc_min > UTC_MAX_MINUTES) app->utc_min = UTC_MIN_MINUTES;
        break;
    case SET_DIGITS:
        app->digits_pad = app->digits_pad ? 0 : 1;
        break;
    default:
        app->lock_idx = (uint8_t)((app->lock_idx + 1) % LOCK_COUNT);
        break;
    }
    settings_save(app);
}

// Returns false when the app should exit.
static bool handle_password_input(App* app, const InputEvent* event) {
    const LangStrings* s = LANGUAGES[app->lang];
    size_t charset_len = strlen(PW_CHARSET);

    switch(event->key) {
    case InputKeyUp:
        app->pw_cur = (uint8_t)((app->pw_cur + charset_len - 1) % charset_len);
        break;
    case InputKeyDown:
        app->pw_cur = (uint8_t)((app->pw_cur + 1) % charset_len);
        break;
    case InputKeyRight:
        if(app->pw_len < PW_MAX) {
            app->pw[app->pw_len++] = PW_CHARSET[app->pw_cur];
            app->pw[app->pw_len] = 0;
        }
        break;
    case InputKeyLeft:
        if(app->pw_len) app->pw[--app->pw_len] = 0;
        break;
    case InputKeyOk:
        if(app->screen == ScreenCreate) {
            if(app->pw_len < PW_MIN) {
                set_msg(app, s->msg_short);
            } else {
                memcpy(app->pw_first, app->pw, sizeof(app->pw));
                secure_zero(app->pw, sizeof(app->pw));
                app->pw_len = 0;
                app->screen = ScreenConfirm;
            }
        } else if(app->screen == ScreenConfirm) {
            if(strcmp(app->pw, app->pw_first) != 0) {
                wipe_password(app);
                set_msg(app, s->msg_mismatch);
                app->screen = ScreenCreate;
            } else {
                app->pending = ActCreate;
            }
        } else if(app->pw_len > 0 && !is_waiting(app)) {
            app->pending = ActUnlock;
        }
        break;
    case InputKeyBack:
        if(app->screen == ScreenConfirm) {
            wipe_password(app);
            app->screen = ScreenCreate;
        } else {
            return false;
        }
        break;
    default:
        break;
    }
    return true;
}

static bool handle_main_input(App* app, const InputEvent* event) {
    switch(event->key) {
    case InputKeyRight:
        app->page = (uint8_t)((app->page + 1) % PAGE_COUNT);
        break;
    case InputKeyLeft:
        app->page = (uint8_t)((app->page + PAGE_COUNT - 1) % PAGE_COUNT);
        break;
    case InputKeyDown:
    case InputKeyUp: {
        int step = event->key == InputKeyDown ? 1 : -1;
        if(app->page == PAGE_CODES && app->acc_count) {
            app->sel = (uint8_t)((app->sel + step + app->acc_count) % app->acc_count);
        } else if(app->page == PAGE_SETTINGS) {
            app->settings_sel = (uint8_t)((app->settings_sel + step + SETTINGS_ROWS) % SETTINGS_ROWS);
        }
        break;
    }
    case InputKeyOk:
        if(app->page == PAGE_CODES && app->acc_count) {
            app->pending = ActType;
        } else if(app->page == PAGE_IMPORT) {
            app->pending = ActImport;
        } else if(app->page == PAGE_SETTINGS) {
            settings_change(app);
        }
        break;
    case InputKeyBack:
        if(app->page != PAGE_CODES) {
            app->page = PAGE_CODES;
        } else {
            return false;
        }
        break;
    default:
        break;
    }
    return true;
}

// Returns false when the app should exit.
static bool handle_input(App* app, const InputEvent* event) {
    if(event->type == InputTypeLong && event->key == InputKeyBack) return false;
    if(!app->selftest_ok) return !(event->type == InputTypeShort && event->key == InputKeyBack);
    bool repeatable = event->key == InputKeyUp || event->key == InputKeyDown;
    if(event->type != InputTypeShort && !(event->type == InputTypeRepeat && repeatable)) {
        return true;
    }
    app->last_input = furi_get_tick();
    if(app->screen == ScreenMain) return handle_main_input(app, event);
    return handle_password_input(app, event);
}

//======================================================================================================================
// Entry point
//======================================================================================================================

int32_t otp_vault_app(void* p) {
    UNUSED(p);

    App* app = malloc(sizeof(App));
    memset(app, 0, sizeof(App));
    app->lang = 0;
    for(size_t i = 0; i < LANGUAGE_COUNT; i++) {
        if(strcmp(LANGUAGES[i]->lang_name, "English") == 0) app->lang = (uint8_t)i;
    }
    app->utc_min = 60;
    app->lock_idx = LOCK_DEFAULT_IDX;
    app->mutex = furi_mutex_alloc(FuriMutexTypeNormal);
    app->queue = furi_message_queue_alloc(8, sizeof(InputEvent));
    app->storage = furi_record_open(RECORD_STORAGE);

    settings_load(app);
    app->selftest_step = run_selftest();
    app->selftest_ok = app->selftest_step == 0;
    selftest_log(app);
    app->screen = storage_file_exists(app->storage, VAULT_PATH) ? ScreenUnlock : ScreenCreate;
    app->last_input = furi_get_tick();

    app->view_port = view_port_alloc();
    view_port_draw_callback_set(app->view_port, draw_callback, app);
    view_port_input_callback_set(app->view_port, input_callback, app);
    app->gui = furi_record_open(RECORD_GUI);
    gui_add_view_port(app->gui, app->view_port, GuiLayerFullscreen);

    bool run = true;
    while(run) {
        InputEvent event;
        FuriStatus status = furi_message_queue_get(app->queue, &event, 200);

        furi_mutex_acquire(app->mutex, FuriWaitForever);
        if(status == FuriStatusOk) run = handle_input(app, &event);
        if(!app->selftest_ok && app->pending != ActNone) app->pending = ActNone;

        if(app->screen == ScreenMain &&
           furi_get_tick() - app->last_input > (uint32_t)LOCK_SECONDS[app->lock_idx] * 1000) {
            lock_vault(app);
        }

        Action act = app->pending;
        app->pending = ActNone;
        if(act != ActNone) app->busy = true;
        furi_mutex_release(app->mutex);
        view_port_update(app->view_port);

        if(act != ActNone) {
            // The GUI thread only draws "Working..." while busy is set, so the
            // heavy work below can run without holding the mutex.
            furi_delay_ms(120);
            run_action(app, act);
            furi_mutex_acquire(app->mutex, FuriWaitForever);
            app->busy = false;
            app->last_input = furi_get_tick();
            furi_mutex_release(app->mutex);
            view_port_update(app->view_port);
        }
    }

    gui_remove_view_port(app->gui, app->view_port);
    furi_record_close(RECORD_GUI);
    view_port_free(app->view_port);
    furi_record_close(RECORD_STORAGE);
    furi_message_queue_free(app->queue);
    furi_mutex_free(app->mutex);
    secure_zero(app, sizeof(App));
    free(app);
    return 0;
}
