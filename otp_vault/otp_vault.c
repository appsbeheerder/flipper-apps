static void settings_save(App* app) {
    storage_simply_mkdir(app->storage, DATA_DIR);
    FlipperFormat* ff = flipper_format_file_alloc(app->storage);
    if(flipper_format_file_open_always(ff, SETTINGS_PATH)) {
        uint32_t v;
        flipper_format_write_header_cstr(ff, "OTPvault settings", 1);
        v = app->lang;
        flipper_format_write_uint32(ff, "Language", &v, 1);
        v = (uint32_t)(app->utc_min - UTC_MIN_MINUTES);
        flipper_format_write_uint32(ff, "Utc", &v, 1);
        v = app->digits_pad;
        flipper_format_write_uint32(ff, "Numpad", &v, 1);
        v = LOCK_SECONDS[app->lock_idx];
        flipper_format_write_uint32(ff, "LockSecs", &v, 1);
    }
    flipper_format_free(ff);
}

static void settings_load(App* app) {
    FlipperFormat* ff = flipper_format_file_alloc(app->storage);
    FuriString* header = furi_string_alloc();
    uint32_t version = 0;
    if(flipper_format_file_open_existing(ff, SETTINGS_PATH) &&
       flipper_format_read_header(ff, header, &version)) {
        uint32_t v;
        if(flipper_format_read_uint32(ff, "Language", &v, 1) && v < LANGUAGE_COUNT) {
            app->lang = (uint8_t)v;
        }
        if(flipper_format_read_uint32(ff, "Utc", &v, 1) &&
           v <= (uint32_t)(UTC_MAX_MINUTES - UTC_MIN_MINUTES)) {
            app->utc_min = (int16_t)((int32_t)v + UTC_MIN_MINUTES);
        }
        if(flipper_format_read_uint32(ff, "Numpad", &v, 1)) app->digits_pad = v ? 1 : 0;
        if(flipper_format_read_uint32(ff, "LockSecs", &v, 1)) {
            for(size_t i = 0; i < LOCK_COUNT; i++) {
                if(LOCK_SECONDS[i] == v) app->lock_idx = (uint8_t)i;
            }
        }
    }
    furi_string_free(header);
    flipper_format_free(ff);
}

