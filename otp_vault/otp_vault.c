// Shown instead of everything else when the self-test fails: the crypto code
// cannot be trusted, so the app refuses to create or open a vault.
static void draw_error_screen(Canvas* canvas, const App* app, const LangStrings* s) {
    char text[32];
    canvas_draw_box(canvas, 0, 0, 128, 18);
    canvas_set_color(canvas, ColorWhite);
    canvas_set_font(canvas, FontPrimary);
    canvas_draw_str_aligned(canvas, 64, 9, AlignCenter, AlignCenter, s->err_title);
    canvas_set_color(canvas, ColorBlack);
    canvas_draw_str_aligned(canvas, 64, 33, AlignCenter, AlignCenter, s->err_use);
    canvas_set_font(canvas, FontSecondary);
    snprintf(text, sizeof(text), s->err_step, (unsigned)app->selftest_step);
    canvas_draw_str_aligned(canvas, 64, 46, AlignCenter, AlignCenter, text);
    canvas_draw_str_aligned(canvas, 64, 58, AlignCenter, AlignCenter, s->err_exit);
    canvas_draw_frame(canvas, 0, 0, 128, 64);
}

static void draw_callback(Canvas* canvas, void* ctx) {
    App* app = ctx;
    furi_mutex_acquire(app->mutex, FuriWaitForever);
    const LangStrings* s = LANGUAGES[app->lang];

    canvas_clear(canvas);
    canvas_set_color(canvas, ColorBlack);
    canvas_set_font(canvas, FontSecondary);

    if(!app->selftest_ok) {
        draw_error_screen(canvas, app, s);
    } else if(app->busy) {
        canvas_draw_str_aligned(canvas, 64, 32, AlignCenter, AlignCenter, s->msg_working);
    } else if(app->screen != ScreenMain) {
        draw_password_screen(canvas, app, s);
    } else {
        const char* titles[PAGE_COUNT] = {
            s->title_codes, s->title_import, s->title_settings, s->title_help, s->title_about};
        char indicator[8];
        snprintf(indicator, sizeof(indicator), "%d/%d", app->page + 1, PAGE_COUNT);
        draw_header(canvas, titles[app->page], indicator);

        switch(app->page) {
        case PAGE_CODES:
            draw_codes_page(canvas, app, s);
            break;
        case PAGE_IMPORT:
            draw_import_page(canvas, app, s);
            break;
        case PAGE_SETTINGS:
            draw_settings_page(canvas, app, s);
            break;
        case PAGE_HELP:
            draw_help_page(canvas, s);
            break;
        default:
            draw_about_page(canvas, app, s);
            break;
        }
    }

    furi_mutex_release(app->mutex);
}

static void input_callback(InputEvent* event, void* ctx) {
    App* app = ctx;
    furi_message_queue_put(app->queue, event, 0);
}

