//======================================================================================================================
// Self-test (RFC test vectors; proves the own SHA/HMAC/PBKDF2/TOTP code works)
//======================================================================================================================

static bool check_hex(const uint8_t* data, size_t len, const char* expected) {
    static const char hex[] = "0123456789abcdef";
    if(strlen(expected) != len * 2) return false;
    for(size_t i = 0; i < len; i++) {
        if(expected[2 * i] != hex[data[i] >> 4]) return false;
        if(expected[2 * i + 1] != hex[data[i] & 15]) return false;
    }
    return true;
}

// Returns 0 when everything passed, otherwise the number of the failing step.
static uint8_t run_selftest(void) {
    uint8_t d[SHA256_LEN];
    const uint8_t* abc = (const uint8_t*)"abc";
    const uint8_t* jefe = (const uint8_t*)"Jefe";
    const uint8_t* what = (const uint8_t*)"what do ya want for nothing?";
    size_t what_len = strlen("what do ya want for nothing?");
    Sha1 s1;
    Sha256 s2;

    sha1_init(&s1);
    sha1_update(&s1, abc, 3);
    sha1_final(&s1, d);
    if(!check_hex(d, SHA1_LEN, "a9993e364706816aba3e25717850c26c9cd0d89d")) return 1;

    sha256_init(&s2);
    sha256_update(&s2, abc, 3);
    sha256_final(&s2, d);
    if(!check_hex(d, SHA256_LEN, "ba7816bf8f01cfea414140de5dae2223b00361a396177a9cb410ff61f20015ad"))
        return 2;

    hmac_sha1(jefe, 4, what, what_len, d);
    if(!check_hex(d, SHA1_LEN, "effcdf6ae5eb2fa2d27416d5f184df9c259a7c79")) return 3;

    hmac_sha256(jefe, 4, what, what_len, d);
    if(!check_hex(d, SHA256_LEN, "5bdcc146bf60754e6a042426089575c75a003f089d2739839dec58b964ec3843"))
        return 4;

    pbkdf2_hmac_sha256((const uint8_t*)"password", 8, (const uint8_t*)"salt", 4, 1, d);
    if(!check_hex(d, SHA256_LEN, "120fb6cffcf8b32c43e7225256c4f837a86548c92ccc35480805987cb70be17b"))
        return 5;
    pbkdf2_hmac_sha256((const uint8_t*)"password", 8, (const uint8_t*)"salt", 4, 2, d);
    if(!check_hex(d, SHA256_LEN, "ae4d0c95af6b46d32d0adff928f06dd02a303f8ef3c251dfd6e2d85a95474c43"))
        return 6;

    if(totp_code(OtpSha1, (const uint8_t*)"12345678901234567890", 20, 59, 30, 8) != 94287082u)
        return 7;
    if(totp_code(OtpSha256, (const uint8_t*)"12345678901234567890123456789012", 32, 59, 30, 8) !=
       46119246u)
        return 8;

    uint8_t b32[10];
    if(base32_decode("GEZDGNBVGY3TQOJQ", b32, sizeof(b32)) != 10) return 9;
    if(memcmp(b32, "1234567890", 10) != 0) return 9;

    return 0;
}

// Leaves the result next to the vault so it can be read without the screen.
static void selftest_log(App* app) {
    char text[48];
    if(app->selftest_ok) {
        snprintf(text, sizeof(text), "v%s selftest=OK\n", APP_VERSION);
    } else {
        snprintf(text, sizeof(text), "v%s selftest=FAIL step=%u\n", APP_VERSION, app->selftest_step);
    }
    storage_simply_mkdir(app->storage, DATA_DIR);
    // file_write_all is defined further down; open the file directly here.
    File* f = storage_file_alloc(app->storage);
    if(storage_file_open(f, DATA_DIR "/selftest.txt", FSAM_WRITE, FSOM_CREATE_ALWAYS)) {
        storage_file_write(f, text, strlen(text));
    }
    storage_file_close(f);
    storage_file_free(f);
}

