#define APP_LICENSE "GPLv3"

#define SCREEN_W 128
#define SCREEN_H 64

// Milliseconds between forced redraws, so the live pages (battery, time)
// keep ticking while the user leaves them on screen.
#define REFRESH_MS 1000

#define PAGE_DEVICE 0
#define PAGE_FIRMWARE 1
#define PAGE_BATTERY 2
#define PAGE_STORAGE 3
#define PAGE_IDS 4
#define PAGE_ABOUT 5
#define PAGE_COUNT 6

#define MAX_LINES 5
#define LINE_LENGTH 40
#define HEX_LENGTH 24

#define LANGUAGE_VISIBLE 4

typedef struct {
    const char* lang_name;

    const char* title_device;
    const char* title_firmware;
    const char* title_battery;
    const char* title_storage;
    const char* title_ids;
    const char* title_about;
    const char* title_language;

    const char* lbl_name;
    const char* lbl_model;
    const char* lbl_hw;
    const char* word_target;
    const char* lbl_color;
    const char* color_black;
    const char* color_white;
    const char* color_transparent;
    const char* color_unknown;

    const char* lbl_version;
    const char* lbl_branch;
    const char* lbl_commit;
    const char* lbl_build;

    const char* lbl_level;
    const char* word_healthy;
    const char* lbl_status;
    const char* status_charging;
    const char* status_discharging;
    const char* lbl_voltage;
    const char* lbl_current;

    const char* lbl_total;
    const char* lbl_free;
    const char* lbl_used;
    const char* msg_no_sd;

    const char* lbl_uid;
    const char* lbl_ble;
    const char* lbl_date;
    const char* lbl_time;

    const char* about_version_label;
    const char* about_author_label;
    const char* about_license_label;
    const char* about_hint;
} LangStrings;

